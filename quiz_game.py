# 1. 퀴즈 문제 데이터 (질문과 정답)
# 리스트([]) 안에 딕셔너리({})를 넣어 여러 문제를 관리합니다.
questions = [
    {
        "질문": "고교학점제에서 내신등급은 몇 등급제일까요?",
        "정답": "5등급제"
    },
    {
        "질문": "현재 대한민국의 4년제 대학의 수는?",
        "정답": "192개(대교협 등록 기준)"
    },
    {
        "질문": "2028학년도 대입에서 가장 중요한 서류는?",
        "정답": "학교생활기록부"
    },
    {
        "질문": "수시와 정시 지원 가능 횟수는?",
        "정답": "수시 6회 / 정시 3회. 단 특수목적대학은 횟수 제한에서 제외"
    },
    {
        "질문": "2028학년도 대입에서 가장 눈에 띄는 변화는?",
        "정답": "교과전형과 종합전형 경계 붕괴 / 수시와 정시의 경계 붕괴"
    },
]

# 2. 환영 인사
print("--- 입시 상식 퀴즈 게임을 시작합니다 ---")

# 3. 문제 내기 (반복문 사용)
for q in questions:
    print(f"\n문제: {q['질문']}")
    answer = input("정답을 입력하세요: ")

    if answer == q["정답"]:
        print("정답입니다!!! 🎉")
    else:
        print(f"아쉽네요. 정답은 '{q['정답']}'입니다. 😅")

print("\n--- 모든 문제를 풀었습니다! 고생하셨습니다. ---")